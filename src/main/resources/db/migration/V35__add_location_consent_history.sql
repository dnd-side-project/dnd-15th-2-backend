CREATE TABLE location_consent_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    terms_version VARCHAR(100) NOT NULL,
    action VARCHAR(16) NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_location_consent_history_user
        FOREIGN KEY (user_id) REFERENCES user_account(id) ON DELETE RESTRICT,
    CONSTRAINT ck_location_consent_history_terms_version
        CHECK (char_length(terms_version) BETWEEN 1 AND 100
            AND terms_version !~ '^[[:space:]]|[[:space:]]$'),
    CONSTRAINT ck_location_consent_history_action
        CHECK (action IN ('CONSENT', 'WITHDRAW'))
);

CREATE INDEX ix_location_consent_history_user_latest
    ON location_consent_history (user_id, id DESC);
