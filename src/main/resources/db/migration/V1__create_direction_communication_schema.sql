-- 활성 미처리 수신 용량은 recipient_receive_state.active_unhandled_count로 집계하지만,
-- 그 값의 근거는 capacity_released_at IS NULL인 post_recipient 행 수다. 상태와 해제 시각이
-- 어긋나면 카운터를 재계산할 수 없으므로 둘의 동치를 커밋 시점에 검사한다.
-- T6·T6A·T6B가 상태 전이와 조건부 해제를 서로 다른 문장으로 수행하므로 지연 트리거다.
--
-- NEW를 쓰지 않고 행을 다시 읽는 이유: 지연 AFTER ROW 트리거는 실행 시점만 커밋으로
-- 미룰 뿐, 전달받는 튜플은 자신을 큐에 넣은 문장 당시의 버전이다. NEW로 판정하면
-- "상태 전이 문장" 시점의 중간 상태(해제 전)를 보고 실패한다. 같은 트랜잭션의 최종
-- 상태를 검사해야 하므로 assert_post_has_content와 같은 방식으로 현재 행을 조회한다.
CREATE FUNCTION enforce_post_recipient_capacity_release()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    current_row RECORD;
BEGIN
    SELECT status, capacity_released_at
    INTO current_row
    FROM post_recipient
    WHERE id = NEW.id;

    IF NOT FOUND THEN
        RETURN NEW;
    END IF;

    IF (current_row.status IN ('ANSWERED', 'SKIPPED', 'EXPIRED', 'BLOCKED'))
       <> (current_row.capacity_released_at IS NOT NULL) THEN
        RAISE EXCEPTION
            'post_recipient % status % and capacity_released_at % disagree',
            NEW.id, current_row.status, current_row.capacity_released_at
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

CREATE CONSTRAINT TRIGGER ct_post_recipient_capacity_release
AFTER INSERT OR UPDATE OF status, capacity_released_at ON post_recipient
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION enforce_post_recipient_capacity_release();

CREATE FUNCTION assert_post_has_content(target_post_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM direction_post p
        WHERE p.id = target_post_id
          AND p.status = 'ACTIVE'
          AND NULLIF(btrim(p.body_text), '') IS NULL
          AND NOT EXISTS (
              SELECT 1
              FROM media_attachment ma
              JOIN media_asset m ON m.id = ma.media_id
              WHERE ma.post_id = p.id
                AND m.status = 'READY'
          )
    ) THEN
        RAISE EXCEPTION 'active direction_post % requires body_text or READY media', target_post_id
            USING ERRCODE = '23514';
    END IF;
END;
$$;

CREATE FUNCTION assert_answer_has_content(target_answer_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM answer a
        WHERE a.id = target_answer_id
          AND a.status = 'PUBLISHED'
          AND NULLIF(btrim(a.body_text), '') IS NULL
          AND NOT EXISTS (
              SELECT 1
              FROM media_attachment ma
              JOIN media_asset m ON m.id = ma.media_id
              WHERE ma.answer_id = a.id
                AND m.status = 'READY'
          )
    ) THEN
        RAISE EXCEPTION 'published answer % requires body_text or READY media', target_answer_id
            USING ERRCODE = '23514';
    END IF;
END;
$$;

CREATE FUNCTION enforce_post_has_content()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM assert_post_has_content(OLD.id);
        RETURN OLD;
    END IF;

    PERFORM assert_post_has_content(NEW.id);
    RETURN NEW;
END;
$$;

CREATE CONSTRAINT TRIGGER ct_direction_post_has_content
AFTER INSERT OR UPDATE ON direction_post
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION enforce_post_has_content();

CREATE FUNCTION enforce_answer_has_content()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM assert_answer_has_content(OLD.id);
        RETURN OLD;
    END IF;

    PERFORM assert_answer_has_content(NEW.id);
    RETURN NEW;
END;
$$;

CREATE CONSTRAINT TRIGGER ct_answer_has_content
AFTER INSERT OR UPDATE ON answer
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION enforce_answer_has_content();

-- 첨부를 붙이거나 떼어낸 뒤에도 콘텐츠 조건이 유지되는지 재검사한다.
-- UPDATE로 첨부 대상이 옮겨간 경우 원래 대상도 다시 확인한다.
CREATE FUNCTION enforce_media_attachment_preserves_content()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        IF OLD.post_id IS NOT NULL THEN
            PERFORM assert_post_has_content(OLD.post_id);
        END IF;
        IF OLD.answer_id IS NOT NULL THEN
            PERFORM assert_answer_has_content(OLD.answer_id);
        END IF;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    IF NEW.post_id IS NOT NULL THEN
        PERFORM assert_post_has_content(NEW.post_id);
    END IF;
    IF NEW.answer_id IS NOT NULL THEN
        PERFORM assert_answer_has_content(NEW.answer_id);
    END IF;

    RETURN NEW;
END;
$$;

CREATE CONSTRAINT TRIGGER ct_media_attachment_preserves_content
AFTER INSERT OR UPDATE OR DELETE ON media_attachment
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION enforce_media_attachment_preserves_content();

-- media_id가 media_attachment의 PK이므로 이 미디어의 첨부는 최대 한 건이다.
CREATE FUNCTION enforce_media_status_preserves_content()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    attachment RECORD;
BEGIN
    SELECT post_id, answer_id INTO attachment
    FROM media_attachment
    WHERE media_id = NEW.id;

    IF FOUND THEN
        IF attachment.post_id IS NOT NULL THEN
            PERFORM assert_post_has_content(attachment.post_id);
        END IF;
        IF attachment.answer_id IS NOT NULL THEN
            PERFORM assert_answer_has_content(attachment.answer_id);
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE CONSTRAINT TRIGGER ct_media_status_preserves_content
AFTER UPDATE OF status ON media_asset
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION enforce_media_status_preserves_content();

