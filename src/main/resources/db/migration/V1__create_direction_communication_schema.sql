CREATE FUNCTION enforce_question_text_immutability()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_TABLE_NAME = 'approved_question'
       AND NEW.question_text IS DISTINCT FROM OLD.question_text THEN
        RAISE EXCEPTION 'approved_question.question_text is immutable'
            USING ERRCODE = '23514';
    END IF;

    IF TG_TABLE_NAME = 'question_proposal'
       AND OLD.status <> 'DRAFT'
       AND NEW.proposed_text IS DISTINCT FROM OLD.proposed_text THEN
        RAISE EXCEPTION 'submitted question_proposal.proposed_text is immutable'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER tr_approved_question_text_immutable
BEFORE UPDATE OF question_text ON approved_question
FOR EACH ROW EXECUTE FUNCTION enforce_question_text_immutability();

CREATE TRIGGER tr_question_proposal_text_immutable_after_submit
BEFORE UPDATE OF proposed_text ON question_proposal
FOR EACH ROW EXECUTE FUNCTION enforce_question_text_immutability();

CREATE FUNCTION enforce_direction_post_question_active()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    current_status VARCHAR(30);
BEGIN
    SELECT status INTO current_status
    FROM approved_question
    WHERE id = NEW.approved_question_id;

    IF current_status <> 'ACTIVE' THEN
        RAISE EXCEPTION 'approved_question % must be ACTIVE (current: %)',
            NEW.approved_question_id, current_status
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

CREATE CONSTRAINT TRIGGER ct_direction_post_question_active
