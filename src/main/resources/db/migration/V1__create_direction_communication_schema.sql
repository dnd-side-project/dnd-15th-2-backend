-- 방향으로 연결되는 소통 — 선택 테이블 기준 전체 DDL
-- Target: PostgreSQL 16+ / PostGIS 3+
--
-- 이 파일은 001~004 뒤에 이어서 실행하는 증분 마이그레이션이 아니다.
-- 사용자가 확정한 ERD 테이블 목록을 기준으로 다시 작성한 독립 실행형 기준 DDL이다.
-- 빈 스키마에서 이 파일만 실행하며, 001~004와 같은 스키마에 함께 실행하지 않는다.
--
-- 스키마의 기준(source of truth)은 docs/dbml/direction_communication.dbml이다.
-- 이 파일은 거기서 파생하며, 스키마를 바꿀 때는 DBML을 먼저 고친다.
--
-- ERD 내 상태값 표와 CopyOf* 표는 데이터 테이블이 아니라 값 목록으로 해석해
-- 각 도메인 컬럼의 CHECK 제약으로 옮겼다. 한글 설명형 컬럼명, DEFAULT AS,
-- 이름 없는 ENUM, 타입이 맞지 않는 FK는 PostgreSQL 실행 가능한 이름과 타입으로 교정했다.
--
-- 정책상 숫자 기본값을 두지 않는 항목:
--   * 방향 글의 최소·최대 거리(P02)
--   * 발송당 최초·최대 수신자 수(P03, 애플리케이션 선정 정책)
--   * 방향 글 만료 기간(P04, expires_at 자체는 필수)
--   * 질문 배정 주기와 한 주기당 개수(P15)
--
-- P06 위치 정책(2026-08-03 확정: 1안)
--   짧은 TTL의 정확 좌표를 active_user_presence에 저장하고 외부에는 흐린 값만 제공한다.
--   active_user_presence.position과 post_audience.origin_position은 실제 사용자 좌표를
--   담는 운영 컬럼이며 더 이상 합성 데이터 전용이 아니다. 정확 좌표는 API 응답, 로그,
--   분석 이벤트, Outbox payload에 넣지 않는다. 보존 기간은 P07에서 확정한다.
--
-- P10 연령 정책 승인 전에는 user_private_attribute.age_band를 수집하지 않는다.
--
-- 2026-08-03 스키마 변경
--   1. post_media + answer_media를 media_attachment 한 테이블로 통합했다. media_id를 PK로
--      두어 "한 미디어는 한 콘텐츠에만" 불변식이 트리거 없이 원자적으로 성립한다. 기존
--      count 기반 constraint trigger 2종은 서로의 미커밋 행을 볼 수 없는 두 트랜잭션이
--      같은 미디어를 각각 다른 콘텐츠에 붙일 때 둘 다 통과하는 구멍이 있어 제거했다.
--   2. FK 컬럼 인덱스를 일괄 추가했다. PostgreSQL은 FK에 인덱스를 자동 생성하지 않는다.
--   3. direction_scheme에 status = 'ACTIVE' partial unique를 추가해 같은 code의 두 버전이
--      동시에 ACTIVE가 되는 것을 막았다.
--   4. post_recipient에 상태와 타임스탬프를 묶는 CHECK와 용량 해제 constraint trigger를
--      추가했다. 이 테이블만 상태 대응 제약이 없어 status = 'SKIPPED'인데 skipped_at이
--      비어 있는 행이 허용됐다.

BEGIN;

CREATE EXTENSION IF NOT EXISTS postgis;

-- -----------------------------------------------------------------------------
-- 1. 지역과 계정
-- -----------------------------------------------------------------------------

CREATE TABLE region_code (
    code                    VARCHAR(100) PRIMARY KEY,
    parent_code             VARCHAR(100),
    display_name            TEXT NOT NULL,
    level                   VARCHAR(20) NOT NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT fk_region_code_parent
        FOREIGN KEY (parent_code) REFERENCES region_code (code) ON DELETE RESTRICT,
    CONSTRAINT ck_region_code_not_self_parent
        CHECK (parent_code IS NULL OR parent_code <> code),
    CONSTRAINT ck_region_code_display_name
        CHECK (btrim(display_name) <> ''),
    CONSTRAINT ck_region_code_level
        CHECK (level IN ('COUNTRY', 'REGION', 'CITY', 'DISTRICT')),
    CONSTRAINT ck_region_code_root
        CHECK ((level = 'COUNTRY') = (parent_code IS NULL))
);

COMMENT ON COLUMN region_code.parent_code IS
    '상위 지역 코드. 두 단계 이상의 순환은 지역 코드 적재 트랜잭션에서 차단한다.';

CREATE TABLE user_account (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role                    VARCHAR(20) NOT NULL DEFAULT 'USER',
    status                  VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    coarse_region_code      VARCHAR(100) NOT NULL,
    locale                  VARCHAR(35) NOT NULL,
    timezone                VARCHAR(64) NOT NULL,
    nickname                VARCHAR(50),
    created_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    deleted_at              TIMESTAMPTZ,

    CONSTRAINT fk_user_account_region
        FOREIGN KEY (coarse_region_code) REFERENCES region_code (code) ON DELETE RESTRICT,
    CONSTRAINT ck_user_account_role
        CHECK (role IN ('USER', 'OPERATOR')),
    CONSTRAINT ck_user_account_status
        CHECK (status IN ('ACTIVE', 'BLOCKED', 'DELETED')),
    CONSTRAINT ck_user_account_nickname
        CHECK (nickname IS NULL OR btrim(nickname) <> ''),
    CONSTRAINT ck_user_account_deleted_at
        CHECK (
            (status = 'DELETED' AND deleted_at IS NOT NULL)
            OR (status <> 'DELETED' AND deleted_at IS NULL)
        )
);

CREATE TABLE user_private_attribute (
    user_id                 BIGINT PRIMARY KEY,
    gender                  VARCHAR(20),
    age_band                VARCHAR(20),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT fk_user_private_attribute_user
        FOREIGN KEY (user_id) REFERENCES user_account (id) ON DELETE CASCADE,
    CONSTRAINT ck_user_private_attribute_gender
        CHECK (gender IS NULL OR gender IN ('MALE', 'FEMALE', 'OTHER', 'UNDISCLOSED')),
    CONSTRAINT ck_user_private_attribute_age_band
        CHECK (age_band IS NULL OR age_band IN (
            '10S', '20S', '30S', '40S', '50S', '60S', '70S_PLUS'
        ))
);

COMMENT ON TABLE user_private_attribute IS
    '선택형 민감 속성. P10 승인 전 age_band를 실제 사용자에게 수집하지 않는다.';

CREATE TABLE active_user_presence (
    user_id                 BIGINT PRIMARY KEY,
    position                geography(Point, 4326),
    coarse_cell_id          VARCHAR(100),
    coarse_region_code      VARCHAR(100) NOT NULL,
    accuracy_m              NUMERIC(10, 2),
    receive_allowed         BOOLEAN NOT NULL DEFAULT FALSE,
    location_at             TIMESTAMPTZ NOT NULL,
    expires_at              TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_active_user_presence_user
        FOREIGN KEY (user_id) REFERENCES user_account (id) ON DELETE CASCADE,
    CONSTRAINT fk_active_user_presence_region
        FOREIGN KEY (coarse_region_code) REFERENCES region_code (code) ON DELETE RESTRICT,
    CONSTRAINT ck_active_user_presence_location
        CHECK (num_nonnulls(position, coarse_cell_id) >= 1),
    CONSTRAINT ck_active_user_presence_accuracy
        CHECK (accuracy_m IS NULL OR accuracy_m >= 0),
    CONSTRAINT ck_active_user_presence_expiry
        CHECK (expires_at > location_at)
);

COMMENT ON TABLE active_user_presence IS
    '수신 후보 탐색용 TTL 읽기 모델. 위치 측정 시각과 만료 시각으로 현재성을 판단한다. '
    'P06 1안에 따라 서비스 전체에서 정확 좌표를 보관하는 유일한 곳이며 접근을 매칭 워커로 제한한다.';
COMMENT ON COLUMN active_user_presence.position IS
    'P06 1안 확정에 따라 실제 사용자 좌표를 담는 운영 컬럼. 거리·방위 계산에만 사용하고 '
    'API 응답, 로그, 분석 이벤트, Outbox payload에는 넣지 않는다.';
COMMENT ON COLUMN active_user_presence.coarse_cell_id IS
    '정확 좌표를 대체하지 않고 보조로 두는 공간 셀 식별자. P06 2안을 채택하지 않아 선택 입력이다.';

CREATE TABLE recipient_receive_state (
    user_id                     BIGINT PRIMARY KEY,
    active_unhandled_count      SMALLINT NOT NULL DEFAULT 0,
    recent_received_count       INTEGER NOT NULL DEFAULT 0,
    recent_window_started_at    TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    last_received_at            TIMESTAMPTZ,
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT fk_recipient_receive_state_user
        FOREIGN KEY (user_id) REFERENCES user_account (id) ON DELETE CASCADE,
    CONSTRAINT ck_recipient_receive_state_active_count
        CHECK (active_unhandled_count BETWEEN 0 AND 5),
    CONSTRAINT ck_recipient_receive_state_recent_count
        CHECK (recent_received_count >= 0),
    CONSTRAINT ck_recipient_receive_state_last_received
        CHECK (last_received_at IS NULL OR last_received_at >= recent_window_started_at)
);

COMMENT ON TABLE recipient_receive_state IS
    '활성 미처리 방향 글 5개 상한을 동시성 아래에서 예약하기 위한 사용자별 투영값.';

-- -----------------------------------------------------------------------------
-- 2. 질문 제안, 검토, 승인 질문과 배정
-- -----------------------------------------------------------------------------

CREATE TABLE question_proposal (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposer_id             BIGINT NOT NULL,
    status                  VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    proposed_text           TEXT NOT NULL,
    decision_reason         TEXT,
    submitted_at            TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT fk_question_proposal_proposer
        FOREIGN KEY (proposer_id) REFERENCES user_account (id) ON DELETE RESTRICT,
    CONSTRAINT ck_question_proposal_status
        CHECK (status IN (
            'DRAFT', 'SUBMITTED', 'UNDER_REVIEW', 'APPROVED', 'REJECTED', 'ARCHIVED'
        )),
    CONSTRAINT ck_question_proposal_text
        CHECK (btrim(proposed_text) <> ''),
    CONSTRAINT ck_question_proposal_submission
        CHECK (status = 'DRAFT' OR submitted_at IS NOT NULL)
);

CREATE TABLE question_proposal_review (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id             BIGINT NOT NULL,
    reviewer_id             BIGINT NOT NULL,
    decision                VARCHAR(30) NOT NULL,
    reason                  TEXT,
    reviewed_at             TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT fk_question_proposal_review_proposal
        FOREIGN KEY (proposal_id) REFERENCES question_proposal (id) ON DELETE RESTRICT,
    CONSTRAINT fk_question_proposal_review_reviewer
        FOREIGN KEY (reviewer_id) REFERENCES user_account (id) ON DELETE RESTRICT,
    CONSTRAINT ck_question_proposal_review_decision
        CHECK (decision IN ('APPROVED', 'REJECTED')),
    CONSTRAINT ck_question_proposal_review_reason
        CHECK (decision = 'APPROVED' OR NULLIF(btrim(reason), '') IS NOT NULL)
);

CREATE TABLE approved_question (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_proposal_id      BIGINT,
    source_type             VARCHAR(30) NOT NULL,
    status                  VARCHAR(30) NOT NULL DEFAULT 'PENDING_REVIEW',
    question_text           TEXT NOT NULL,
    answer_format           VARCHAR(20) NOT NULL,
    active_from             TIMESTAMPTZ,
    active_until            TIMESTAMPTZ,
    approved_at             TIMESTAMPTZ,
    approved_by             BIGINT,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT fk_approved_question_source_proposal
        FOREIGN KEY (source_proposal_id) REFERENCES question_proposal (id) ON DELETE RESTRICT,
    CONSTRAINT fk_approved_question_approver
        FOREIGN KEY (approved_by) REFERENCES user_account (id) ON DELETE RESTRICT,
    CONSTRAINT uq_approved_question_source_proposal
        UNIQUE (source_proposal_id),
    CONSTRAINT ck_approved_question_source_type
        CHECK (source_type IN ('OPERATOR', 'USER_PROPOSAL', 'GENERATED_CANDIDATE')),
    CONSTRAINT ck_approved_question_source
        CHECK (
            (source_type = 'USER_PROPOSAL' AND source_proposal_id IS NOT NULL)
            OR (source_type <> 'USER_PROPOSAL' AND source_proposal_id IS NULL)
        ),
    CONSTRAINT ck_approved_question_status
        CHECK (status IN ('PENDING_REVIEW', 'ACTIVE', 'INACTIVE', 'ARCHIVED')),
    CONSTRAINT ck_approved_question_text
        CHECK (btrim(question_text) <> ''),
    CONSTRAINT ck_approved_question_answer_format
        CHECK (answer_format IN ('PHOTO', 'TEXT', 'BOTH')),
    CONSTRAINT ck_approved_question_active_range
        CHECK (active_until IS NULL OR active_from IS NULL OR active_until > active_from),
    CONSTRAINT ck_approved_question_approval
        CHECK (
            status <> 'ACTIVE'
            OR (approved_at IS NOT NULL AND approved_by IS NOT NULL AND active_from IS NOT NULL)
        )
);

COMMENT ON TABLE approved_question IS
    '검토를 통과해 배정과 발송에 사용할 수 있는 불변 질문 문구.';

CREATE TABLE question_assignment_cycle (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT NOT NULL,
    cycle_key               VARCHAR(100) NOT NULL,
    pool_version            VARCHAR(100) NOT NULL,
    status                  VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    starts_at               TIMESTAMPTZ NOT NULL,
    ends_at                 TIMESTAMPTZ NOT NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT fk_question_assignment_cycle_user
        FOREIGN KEY (user_id) REFERENCES user_account (id) ON DELETE RESTRICT,
    CONSTRAINT uq_question_assignment_cycle_user_key
        UNIQUE (user_id, cycle_key),
    CONSTRAINT ck_question_assignment_cycle_status
        CHECK (status IN ('ACTIVE', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_question_assignment_cycle_range
        CHECK (ends_at > starts_at)
);

CREATE TABLE question_assignment (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id                BIGINT NOT NULL,
    approved_question_id    BIGINT NOT NULL,
    display_order           INTEGER NOT NULL,
    assigned_at             TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    first_viewed_at         TIMESTAMPTZ,
    used_at                 TIMESTAMPTZ,

    CONSTRAINT fk_question_assignment_cycle
        FOREIGN KEY (cycle_id) REFERENCES question_assignment_cycle (id) ON DELETE CASCADE,
    CONSTRAINT fk_question_assignment_question
        FOREIGN KEY (approved_question_id) REFERENCES approved_question (id) ON DELETE RESTRICT,
    CONSTRAINT uq_question_assignment_cycle_question
        UNIQUE (cycle_id, approved_question_id),
    CONSTRAINT uq_question_assignment_cycle_order
        UNIQUE (cycle_id, display_order),
    CONSTRAINT ck_question_assignment_display_order
        CHECK (display_order > 0),
    CONSTRAINT ck_question_assignment_viewed_at
        CHECK (first_viewed_at IS NULL OR first_viewed_at >= assigned_at),
    CONSTRAINT ck_question_assignment_used_at
        CHECK (used_at IS NULL OR used_at >= assigned_at)
);

-- -----------------------------------------------------------------------------
-- 3. 방향 정책, 방향 글, 수신 권한, 답변과 미디어
-- -----------------------------------------------------------------------------

CREATE TABLE direction_scheme (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                    VARCHAR(50) NOT NULL,
    version                 INTEGER NOT NULL,
    type                    VARCHAR(30) NOT NULL,
    segment_count           INTEGER,
    start_offset_deg        NUMERIC(7, 3) NOT NULL,
    status                  VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    CONSTRAINT uq_direction_scheme_code_version
        UNIQUE (code, version),
    CONSTRAINT ck_direction_scheme_version
        CHECK (version > 0),
    CONSTRAINT ck_direction_scheme_type
        CHECK (type IN ('EQUAL_SEGMENTS', 'CONTINUOUS')),
    CONSTRAINT ck_direction_scheme_segment_count
        CHECK (
            (type = 'EQUAL_SEGMENTS' AND segment_count > 0)
            OR (type = 'CONTINUOUS' AND segment_count IS NULL)
        ),
    CONSTRAINT ck_direction_scheme_start_offset
        CHECK (start_offset_deg >= 0 AND start_offset_deg < 360),
    CONSTRAINT ck_direction_scheme_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'ARCHIVED'))
);

CREATE TABLE direction_segment (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheme_id               BIGINT NOT NULL,
    segment_key             VARCHAR(20) NOT NULL,
    display_name            VARCHAR(50) NOT NULL,
    center_bearing_deg      NUMERIC(7, 3) NOT NULL,
    angular_width_deg       NUMERIC(7, 3) NOT NULL,
    sort_order              INTEGER NOT NULL,

    CONSTRAINT fk_direction_segment_scheme
        FOREIGN KEY (scheme_id) REFERENCES direction_scheme (id) ON DELETE RESTRICT,
    CONSTRAINT uq_direction_segment_key
        UNIQUE (scheme_id, segment_key),
    CONSTRAINT uq_direction_segment_order
        UNIQUE (scheme_id, sort_order),
    CONSTRAINT ck_direction_segment_center
        CHECK (center_bearing_deg >= 0 AND center_bearing_deg < 360),
    CONSTRAINT ck_direction_segment_width
        CHECK (angular_width_deg > 0 AND angular_width_deg <= 360),
    CONSTRAINT ck_direction_segment_order
        CHECK (sort_order >= 0)
);

CREATE TABLE media_asset (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id                BIGINT NOT NULL,
    status                  VARCHAR(30) NOT NULL DEFAULT 'UPLOADING',
    storage_key             VARCHAR(500) NOT NULL,
    mime_type               VARCHAR(100) NOT NULL,
    byte_size               BIGINT NOT NULL,
    checksum                VARCHAR(128) NOT NULL,
    exif_stripped           BOOLEAN NOT NULL DEFAULT FALSE,
    moderation_status       VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    created_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    deleted_at              TIMESTAMPTZ,

    CONSTRAINT fk_media_asset_owner
        FOREIGN KEY (owner_id) REFERENCES user_account (id) ON DELETE RESTRICT,
    CONSTRAINT uq_media_asset_id_owner
        UNIQUE (id, owner_id),
    CONSTRAINT uq_media_asset_storage_key
        UNIQUE (storage_key),
    CONSTRAINT ck_media_asset_status
        CHECK (status IN ('UPLOADING', 'READY', 'REJECTED', 'DELETED')),
    CONSTRAINT ck_media_asset_moderation
        CHECK (moderation_status IN ('PENDING', 'PASSED', 'REVIEW_HELD', 'REJECTED')),
    CONSTRAINT ck_media_asset_size
        CHECK (byte_size > 0),
    CONSTRAINT ck_media_asset_deleted_at
        CHECK ((status = 'DELETED') = (deleted_at IS NOT NULL))
);

CREATE TABLE direction_post (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id               BIGINT NOT NULL,
    approved_question_id    BIGINT NOT NULL,
    status                  VARCHAR(30) NOT NULL DEFAULT 'SUBMITTED',
    idempotency_key         VARCHAR(200) NOT NULL,
    body_text               TEXT,
    coarse_region_code      VARCHAR(100) NOT NULL,
    moderation_status       VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    submitted_at            TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    published_at            TIMESTAMPTZ,
    expires_at              TIMESTAMPTZ NOT NULL,
    deleted_at              TIMESTAMPTZ,

    CONSTRAINT fk_direction_post_sender
        FOREIGN KEY (sender_id) REFERENCES user_account (id) ON DELETE RESTRICT,
    CONSTRAINT fk_direction_post_question
        FOREIGN KEY (approved_question_id) REFERENCES approved_question (id) ON DELETE RESTRICT,
    CONSTRAINT fk_direction_post_region
        FOREIGN KEY (coarse_region_code) REFERENCES region_code (code) ON DELETE RESTRICT,
    CONSTRAINT uq_direction_post_idempotency
        UNIQUE (sender_id, idempotency_key),
    CONSTRAINT uq_direction_post_id_sender
        UNIQUE (id, sender_id),
    CONSTRAINT ck_direction_post_status
        CHECK (status IN (
            'SUBMITTED', 'SAFETY_CHECKING', 'MATCHING', 'ACTIVE', 'MATCH_FAILED',
            'REVIEW_HELD', 'REJECTED', 'EXPIRED', 'HIDDEN', 'DELETED'
        )),
    CONSTRAINT ck_direction_post_moderation
        CHECK (moderation_status IN ('PENDING', 'PASSED', 'REVIEW_HELD', 'REJECTED')),
    CONSTRAINT ck_direction_post_body
        CHECK (body_text IS NULL OR btrim(body_text) <> ''),
    CONSTRAINT ck_direction_post_expiry
        CHECK (expires_at > submitted_at),
    CONSTRAINT ck_direction_post_published_at
        CHECK (status <> 'ACTIVE' OR published_at IS NOT NULL),
    CONSTRAINT ck_direction_post_deleted_at
        CHECK ((status = 'DELETED') = (deleted_at IS NOT NULL))
);

CREATE TABLE post_audience (
    post_id                     BIGINT PRIMARY KEY,
    direction_scheme_id         BIGINT NOT NULL,
    selected_segment_key        VARCHAR(20) NOT NULL,
    center_bearing_deg          NUMERIC(7, 3) NOT NULL,
    angular_width_deg           NUMERIC(7, 3) NOT NULL,
    min_distance_m              BIGINT NOT NULL,
    max_distance_m              BIGINT NOT NULL,
    origin_position             geography(Point, 4326),
    origin_cell_id              VARCHAR(100),
    snapshotted_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT fk_post_audience_post
        FOREIGN KEY (post_id) REFERENCES direction_post (id) ON DELETE CASCADE,
    CONSTRAINT fk_post_audience_segment
        FOREIGN KEY (direction_scheme_id, selected_segment_key)
        REFERENCES direction_segment (scheme_id, segment_key) ON DELETE RESTRICT,
    CONSTRAINT ck_post_audience_center
        CHECK (center_bearing_deg >= 0 AND center_bearing_deg < 360),
    CONSTRAINT ck_post_audience_width
        CHECK (angular_width_deg > 0 AND angular_width_deg <= 360),
    CONSTRAINT ck_post_audience_distance
        CHECK (min_distance_m >= 0 AND max_distance_m > min_distance_m),
    CONSTRAINT ck_post_audience_origin
        CHECK (num_nonnulls(origin_position, origin_cell_id) >= 1)
