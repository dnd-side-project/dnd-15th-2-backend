-- #375: 운영자 접근 기록. 로그인 결과, 로그아웃, 운영자 API 호출을 한 행씩 남긴다.
--
-- operator_action_audit(V20)와 섞지 않는다. 그 테이블은 필터링 authority 변경의 근거
-- 원장이라 reason·policy_version이 필수이고, 접근 기록에는 그런 값이 없다.
--
-- append-only다. 애플리케이션에 수정·삭제 경로를 두지 않는다. DB 권한으로 막는 것은
-- 운영 인프라 작업(I4)에서 다룬다.
--
-- user_account FK를 두지 않는다. 운영자 계정이 삭제·탈퇴해도 기록은 남아야 하고,
-- cascade로 지워져서도 안 된다. 계정을 특정하지 못한 로그인 실패는 operator_user_id가
-- NULL이다.
--
-- 비밀번호, 세션 ID, CSRF 토큰, 요청 본문, query string은 담지 않는다. request_path는
-- query를 뺀 요청 URI다.
CREATE TABLE operator_access_log (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type          VARCHAR(30) NOT NULL,
    operator_user_id    BIGINT,
    client_address      VARCHAR(64) NOT NULL,
    http_method         VARCHAR(16) NOT NULL,
    request_path        VARCHAR(512) NOT NULL,
    http_status         SMALLINT NOT NULL,
    result_code         VARCHAR(30),
    occurred_at         TIMESTAMPTZ NOT NULL,

    CONSTRAINT ck_operator_access_log_event_type
        CHECK (event_type IN ('LOGIN_SUCCEEDED', 'LOGIN_FAILED', 'LOGOUT', 'API_CALL')),
    CONSTRAINT ck_operator_access_log_operator
        CHECK (operator_user_id IS NULL OR operator_user_id > 0),
    -- 운영자를 특정하지 못할 수 있는 것은 로그인 실패뿐이다.
    CONSTRAINT ck_operator_access_log_operator_required
        CHECK (event_type = 'LOGIN_FAILED' OR operator_user_id IS NOT NULL),
    CONSTRAINT ck_operator_access_log_client_address
        CHECK (btrim(client_address) <> ''),
    CONSTRAINT ck_operator_access_log_http_method
        CHECK (btrim(http_method) <> ''),
    CONSTRAINT ck_operator_access_log_request_path
        CHECK (btrim(request_path) <> ''),
    CONSTRAINT ck_operator_access_log_http_status
        CHECK (http_status BETWEEN 100 AND 599),
    CONSTRAINT ck_operator_access_log_result_code
        CHECK (result_code IS NULL OR btrim(result_code) <> '')
);

-- 기간 조회와 보존 기간이 지난 행의 파기에 쓴다. 운영자별 조회 인덱스는 조회 경로가
-- 생길 때 추가한다.
CREATE INDEX operator_access_log_occurred_at_idx
    ON operator_access_log (occurred_at);

COMMENT ON TABLE operator_access_log IS
    '운영자 접근 기록(#375). 로그인 결과·로그아웃·운영자 API 호출. append-only';
COMMENT ON COLUMN operator_access_log.operator_user_id IS
    '운영자 계정 id. 계정을 특정하지 못한 로그인 실패만 NULL';
COMMENT ON COLUMN operator_access_log.client_address IS
    '연결 주소(remoteAddr). X-Forwarded-For는 쓰지 않는다';
COMMENT ON COLUMN operator_access_log.request_path IS
    'query string을 뺀 요청 URI';
COMMENT ON COLUMN operator_access_log.result_code IS
    '로그인 실패의 오류 코드(AUT-APP-xxx). 그 밖의 이벤트는 NULL';
